"""Legality checker: is a candidate a valid, semantics-preserving graph transformation of G0?

Static checks (no GPU, milliseconds):
  * interface: ``class Model``; optional INDUCTOR_CONFIG / COMPILE_MODE / convert_weights
  * transformation space: graph-level PyTorch only -- no hand-written kernels or extensions
    (triton, CUDA/C++ extensions, ctypes, custom ops), no subprocess / file / network access
  * no hidden state: no ``global`` writes, no attribute assignment on ``self`` inside forward
  * INDUCTOR_CONFIG keys in the whitelist and present in this torch version; COMPILE_MODE allowed

Dynamic checks (worker subprocess, GPU):
  * candidate loads the reference weights (directly or via convert_weights)
  * dynamo traces forward with zero graph breaks
  * outputs match eager G0 on several random input seeds: structure, shape, dtype, NaN/Inf
    positions and values within the task tolerance; if the direct comparison fails, a
    high-precision oracle (G0 in float64) decides whether the candidate is at least as
    accurate as G0 itself (reordered fp16 reductions legitimately change rounding)
  * inputs are not mutated (unless G0 mutates them identically)
"""

from __future__ import annotations

import ast
import time
from pathlib import Path

from .task import ALLOWED_COMPILE_MODES, INDUCTOR_CONFIG_WHITELIST

FORBIDDEN_MODULES = {
    "triton", "ctypes", "cffi", "numba", "cupy", "pycuda", "cuda", "tvm", "tensorrt", "torch_tensorrt",
    "subprocess", "socket", "requests", "urllib", "multiprocessing", "threading", "pickle", "shutil",
    "torch.utils.cpp_extension", "torch.cuda.nvtx", "torch._inductor", "torch._dynamo", "torch.library",
    "importlib", "jax", "tilelang", "cutlass", "flashinfer", "flash_attn", "xformers", "apex", "liger_kernel",
}
FORBIDDEN_ATTRS = {
    "load_inline", "cpp_extension", "load_library", "custom_op", "triton_op", "wrap_triton", "register_kernel",
    "register_fake", "disable", "allow_in_graph", "assume_constant_result", "jit", "system", "popen", "exec",
    "compile", "__import__", "_inductor", "_dynamo", "cudart", "set_flags",
}
FORBIDDEN_NAMES = {"exec", "eval", "compile", "__import__", "open", "globals", "setattr"}


def _module_name(node) -> list[str]:
    if isinstance(node, ast.Import):
        return [a.name for a in node.names]
    if isinstance(node, ast.ImportFrom):
        base = node.module or ""
        return [base] + [f"{base}.{a.name}" for a in node.names]
    return []


def static_check(cand_path: str | Path, is_task: bool = False) -> dict:
    src = Path(cand_path).read_text()
    errors: list[str] = []
    warnings: list[str] = []
    try:
        tree = ast.parse(src)
    except SyntaxError as e:
        return {"ok": False, "errors": [f"syntax error: {e}"], "warnings": []}

    top_names = set()
    model_cls = None
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            top_names.add(node.name)
            if node.name == "Model":
                model_cls = node
        elif isinstance(node, ast.FunctionDef):
            top_names.add(node.name)
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    top_names.add(t.id)
    if model_cls is None:
        errors.append("missing `class Model(nn.Module)`")
    if is_task:
        for fn in ("get_inputs", "get_init_inputs"):
            if fn not in top_names:
                errors.append(f"task must define `{fn}()`")

    for node in ast.walk(tree):
        for mod in _module_name(node):
            for bad in FORBIDDEN_MODULES:
                if mod == bad or mod.startswith(bad + "."):
                    errors.append(f"line {node.lineno}: forbidden import `{mod}` (only graph-level PyTorch rewrites "
                                  "are allowed; kernels are generated by TorchInductor)")
        if isinstance(node, ast.Attribute) and node.attr in FORBIDDEN_ATTRS:
            errors.append(f"line {node.lineno}: forbidden attribute `.{node.attr}`")
        if isinstance(node, ast.Name) and node.id in FORBIDDEN_NAMES and isinstance(getattr(node, "ctx", None), ast.Load):
            errors.append(f"line {node.lineno}: forbidden builtin `{node.id}`")
        if isinstance(node, (ast.Global, ast.Nonlocal)):
            errors.append(f"line {node.lineno}: `global`/`nonlocal` state is not allowed (graphs must be pure)")

    if model_cls is not None:
        for item in model_cls.body:
            if isinstance(item, ast.FunctionDef) and item.name == "forward":
                for sub in ast.walk(item):
                    targets = []
                    if isinstance(sub, ast.Assign):
                        targets = sub.targets
                    elif isinstance(sub, (ast.AugAssign, ast.AnnAssign)):
                        targets = [sub.target]
                    for t in targets:
                        for tt in ast.walk(t):
                            if isinstance(tt, ast.Attribute) and isinstance(tt.value, ast.Name) \
                                    and tt.value.id == "self":
                                errors.append(f"line {sub.lineno}: forward assigns `self.{tt.attr}` "
                                              "(stateful caching across calls is not allowed)")
                    if isinstance(sub, ast.Call) and isinstance(sub.func, ast.Attribute) \
                            and sub.func.attr in ("register_buffer", "register_parameter"):
                        errors.append(f"line {sub.lineno}: forward registers state")

    if not is_task:
        cfg_errors, cfg = _config_check(tree)
        errors.extend(cfg_errors)
        if "TOLERANCE" in top_names:
            warnings.append("candidate TOLERANCE is ignored; the task tolerance is used")
    return {"ok": not errors, "errors": sorted(set(errors)), "warnings": warnings}


def _literal(tree, name):
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in node.targets):
            try:
                return True, ast.literal_eval(node.value)
            except ValueError:
                return True, ValueError(f"{name} must be a literal")
    return False, None


def _config_check(tree) -> tuple[list[str], dict]:
    errors = []
    has, cfg = _literal(tree, "INDUCTOR_CONFIG")
    if has:
        if isinstance(cfg, Exception) or not isinstance(cfg, dict):
            errors.append("INDUCTOR_CONFIG must be a literal dict")
            cfg = {}
        else:
            try:
                from torch._inductor import config as icfg

                known = set(icfg._config.keys()) if hasattr(icfg, "_config") else None
            except Exception:
                known = None
            for k in cfg:
                if k not in INDUCTOR_CONFIG_WHITELIST:
                    errors.append(f"INDUCTOR_CONFIG key `{k}` is not whitelisted "
                                  f"(see cage.task.INDUCTOR_CONFIG_WHITELIST)")
                elif known is not None and k not in known:
                    errors.append(f"INDUCTOR_CONFIG key `{k}` does not exist in this torch version")
    else:
        cfg = {}
    has_mode, mode = _literal(tree, "COMPILE_MODE")
    if has_mode and mode not in ALLOWED_COMPILE_MODES:
        errors.append(f"COMPILE_MODE {mode!r} not in {ALLOWED_COMPILE_MODES}")
    return errors, cfg


# ---------------------------------------------------------------------- dynamic (worker side)

def _compare(ref_leaves, cand_leaves, tol_fn) -> tuple[bool, list[str], list[dict]]:
    import torch

    errs, stats = [], []
    if len(ref_leaves) != len(cand_leaves):
        return False, [f"output count {len(cand_leaves)} != reference {len(ref_leaves)}"], stats
    for i, (r, c) in enumerate(zip(ref_leaves, cand_leaves)):
        if isinstance(r, torch.Tensor) != isinstance(c, torch.Tensor):
            errs.append(f"output[{i}] type {type(c).__name__} != {type(r).__name__}")
            continue
        if not isinstance(r, torch.Tensor):
            if r != c:
                errs.append(f"output[{i}] value {c!r} != {r!r}")
            continue
        if r.shape != c.shape:
            errs.append(f"output[{i}] shape {tuple(c.shape)} != {tuple(r.shape)}")
            continue
        if r.dtype != c.dtype:
            errs.append(f"output[{i}] dtype {c.dtype} != {r.dtype}")
            continue
        if r.is_floating_point() or r.is_complex():
            rn, cn = torch.isnan(r), torch.isnan(c)
            if not torch.equal(rn, cn):
                errs.append(f"output[{i}] NaN positions differ ({int(rn.sum())} vs {int(cn.sum())})")
                continue
            ri, ci = torch.isinf(r), torch.isinf(c)
            if not torch.equal(ri, ci) or not torch.equal(r[ri], c[ci]):
                errs.append(f"output[{i}] Inf positions differ")
                continue
            fin = torch.isfinite(r)
            rf, cf = r[fin].double(), c[fin].double()
            tol = tol_fn(r.dtype)
            diff = (rf - cf).abs()
            bound = tol["atol"] + tol["rtol"] * rf.abs()
            bad = (diff > bound)
            st = {"output": i, "max_abs_err": float(diff.max()) if diff.numel() else 0.0,
                  "mismatch_frac": float(bad.float().mean()) if bad.numel() else 0.0, **tol}
            stats.append(st)
            if bad.any():
                errs.append(f"output[{i}] mismatch: max_abs_err={st['max_abs_err']:.3g} "
                            f"mismatched={st['mismatch_frac'] * 100:.3f}% (atol={tol['atol']}, rtol={tol['rtol']})")
        else:
            if not torch.equal(r, c):
                errs.append(f"output[{i}] integer/bool values differ ({int((r != c).sum())} elements)")
    return not errs, errs, stats


def _oracle_check(ref_model, inputs, ref_leaves, cand_leaves) -> tuple[bool, str]:
    """Accept if candidate error vs a float64 oracle is <= 2x G0's own error (+ tiny slack)."""
    import copy

    import torch

    from .task import flatten_outputs

    try:
        hp = copy.deepcopy(ref_model).double()
        hp_inputs = [x.double() if isinstance(x, torch.Tensor) and x.is_floating_point() else x for x in inputs]
        with torch.no_grad():
            oracle = flatten_outputs(hp(*hp_inputs))
    except Exception as e:
        return False, f"oracle unavailable ({type(e).__name__})"
    msgs = []
    ok = True
    for i, (o, r, c) in enumerate(zip(oracle, ref_leaves, cand_leaves)):
        if not (isinstance(o, torch.Tensor) and o.is_floating_point()):
            continue
        fin = torch.isfinite(o) & torch.isfinite(r.double()) & torch.isfinite(c.double())
        e_ref = (r.double()[fin] - o[fin]).abs()
        e_cand = (c.double()[fin] - o[fin]).abs()
        ref_max, cand_max = float(e_ref.max()), float(e_cand.max())
        ref_mean, cand_mean = float(e_ref.mean()), float(e_cand.mean())
        slack = 1e-6 * float(o[fin].abs().max())
        good = cand_max <= 2.0 * ref_max + slack and cand_mean <= 2.0 * ref_mean + slack
        msgs.append(f"output[{i}] oracle err: cand max={cand_max:.3g} mean={cand_mean:.3g} vs "
                    f"G0 max={ref_max:.3g} mean={ref_mean:.3g} -> {'ok' if good else 'WORSE'}")
        ok &= good
    return ok, "; ".join(msgs)


def dynamic_check(task_path: str, cand_path: str, seeds: int = 3, compiled: bool = True) -> dict:
    import torch

    from .task import (build_candidate, build_reference, clone_inputs, compile_model, flatten_outputs,
                       inductor_config, load_spec, make_inputs, tolerance_for)

    t0 = time.time()
    task = load_spec(task_path)
    cand = load_spec(cand_path)
    errors, notes, stats = [], [], []
    ref = build_reference(task)
    try:
        model = build_candidate(task, cand, ref)
    except Exception as e:
        return {"ok": False, "errors": [f"weight loading: {e}"], "wall_s": round(time.time() - t0, 2)}

    inputs0 = make_inputs(task, 0)
    graph_breaks = None
    try:
        torch._dynamo.reset()
        with torch.no_grad():
            ex = torch._dynamo.explain(model)(*clone_inputs(inputs0))
        graph_breaks = int(ex.graph_break_count)
        if graph_breaks:
            reasons = [str(getattr(r, "reason", r))[:200] for r in ex.break_reasons[:5]]
            errors.append(f"{graph_breaks} graph break(s): {reasons}")
        torch._dynamo.reset()
    except Exception as e:
        errors.append(f"dynamo cannot trace forward: {type(e).__name__}: {str(e)[:300]}")

    run_fn = model
    ctx = inductor_config(cand.inductor_config if compiled else None)
    ctx.__enter__()
    compile_s = None
    try:
        if compiled and not errors:
            run_fn = compile_model(model, cand, fullgraph=True)
        for seed in range(seeds):
            inputs = make_inputs(task, seed)
            ref_in, cand_in = clone_inputs(inputs), clone_inputs(inputs)
            with torch.no_grad():
                ref_out = flatten_outputs(ref(*ref_in))
                ts = time.time()
                if hasattr(torch.compiler, "cudagraph_mark_step_begin"):
                    torch.compiler.cudagraph_mark_step_begin()
                cand_out = flatten_outputs(run_fn(*cand_in))
                cand_out = [x.clone() if isinstance(x, torch.Tensor) else x for x in cand_out]
                if seed == 0 and compiled:
                    torch.cuda.synchronize()
                    compile_s = round(time.time() - ts, 2)
            ok, errs, st = _compare(ref_out, cand_out, lambda dt: tolerance_for(task, dt))
            stats.extend({"seed": seed, **s} for s in st)
            if not ok:
                ok2, msg = _oracle_check(ref, clone_inputs(inputs), ref_out, cand_out)
                if ok2:
                    notes.append(f"seed {seed}: direct comparison exceeded tolerance but accepted by "
                                 f"float64 oracle ({msg})")
                else:
                    errors.extend(f"seed {seed}: {e}" for e in errs)
                    if msg:
                        errors.append(f"seed {seed}: {msg}")
                    break
            for j, (a, b) in enumerate(zip(ref_in, cand_in)):
                if isinstance(a, torch.Tensor) and not torch.equal(a, b):
                    errors.append(f"seed {seed}: candidate mutates input[{j}] differently from G0")
            if errors:
                break
    except Exception as e:
        errors.append(f"{'compiled' if compiled else 'eager'} run failed: {type(e).__name__}: {str(e)[:500]}")
    finally:
        ctx.__exit__(None, None, None)
    return {
        "ok": not errors,
        "errors": errors,
        "notes": notes,
        "graph_breaks": graph_breaks,
        "compiled": compiled,
        "compile_s": compile_s,
        "seeds": seeds,
        "max_abs_err": max((s["max_abs_err"] for s in stats), default=0.0),
        "wall_s": round(time.time() - t0, 2),
    }


def render(static: dict, dynamic: dict | None) -> str:
    ok = static["ok"] and (dynamic is None or dynamic.get("ok"))
    out = [f"== LEGALITY: {'PASS' if ok else 'FAIL'} =="]
    for e in static["errors"]:
        out.append(f"  [static] ERROR {e}")
    for w in static.get("warnings", []):
        out.append(f"  [static] warn  {w}")
    if dynamic is not None:
        for e in dynamic.get("errors", []) or ([dynamic["error"]] if dynamic.get("error") else []):
            out.append(f"  [dynamic] ERROR {e}")
        if dynamic.get("stderr_tail"):
            out.append("  [dynamic] stderr tail:\n" + dynamic["stderr_tail"])
        if dynamic.get("traceback"):
            out.append("  [dynamic] traceback:\n" + dynamic["traceback"])
        for n in dynamic.get("notes", []):
            out.append(f"  [dynamic] note  {n}")
        if dynamic.get("ok"):
            out.append(f"  graph_breaks={dynamic.get('graph_breaks')} compiled={dynamic.get('compiled')} "
                       f"seeds={dynamic.get('seeds')} max_abs_err={dynamic.get('max_abs_err'):.3g} "
                       f"compile_s={dynamic.get('compile_s')}")
    return "\n".join(out)
